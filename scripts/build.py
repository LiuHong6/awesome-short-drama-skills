def tr(obj: dict, key: str, lang: str):
    """取字段的当前语言版本：英文取 key_en，没有就退回中文。"""
    return (obj.get(f"{key}_en") or obj.get(key)) if lang == "en" else obj.get(key)


def gh_url(repo: str) -> str:
    return f"https://github.com/{repo}"


def display_name(s: dict) -> str:
    return s.get("name") or s["repo"].split("/", 1)[1]


def fmt_stars(n: int | None) -> str:
    if n is None:
        return "—"
    return f"{n / 1000:.1f}k".replace(".0k", "k") if n >= 1000 else str(n)


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def sort_key(s: dict, meta: dict):
    stars = meta.get(s["repo"], {}).get("stars", -1)
    return (s.get("tier") != "featured", -stars, display_name(s).lower())


def status_mark(m: dict, ref: dt.date | None) -> str:
    if m.get("status") == "missing":
        return " ⚠️"
    if m.get("archived"):
        return " 📦"
    if ref and m.get("pushed_at") and (ref - dt.date.fromisoformat(m["pushed_at"])).days > STALE_DAYS:
        return " 💤"
    return ""


def name_line(s: dict, m: dict, ref: dt.date | None) -> str:
    star = "🌟 " if s.get("tier") == "featured" else ""
    return f"{star}**[{display_name(s)}]({gh_url(s['repo'])})** · ★ {fmt_stars(m.get('stars'))}"


def meta_line(s: dict, m: dict, ref: dt.date | None, ui: dict) -> str:
    sub = [ui["updated"].format(f"{m.get('pushed_at') or '—'}{status_mark(m, ref)}")]
    if s["format"] in ui["format_badge"]:
        sub.append(ui["format_badge"][s["format"]])
    sub.append(ui["lang"][s["lang"]])
    if m.get("skill_count", 0) > 1:
        sub.append(ui["skill_count"].format(f"{m['skill_count']}{'+' if m.get('skill_count_truncated') else ''}"))
    if m.get("license"):
        sub.append(m["license"])
    return " · ".join(sub)


def desc_block(s: dict, models: dict, stage_text: str, meta: str, ui: dict, lang: str) -> str:
    text = cell(tr(s, "desc", lang)) + f"<br><sub>{ui['stages']}{stage_text}</sub><br><sub>{meta}</sub>"
    if s.get("models"):
        text += f"<br><sub>🎬 {' · '.join(models[md] for md in s['models'])}</sub>"
    if s.get("note"):
        text += f"<br><sub>💡 {cell(tr(s, 'note', lang))}</sub>"
    return text


def install_cmd(s: dict) -> str | None:
    if s.get("install"):
        return s["install"]
    if s["format"] == "skill":
        return f"npx skills add {s['repo']}"
    return None


def by_stars(items, meta: dict) -> list[dict]:
    return sorted(items, key=lambda s: -meta.get(s["repo"], {}).get("stars", -1))


def render_packs(packs: list[dict], by_repo: dict, ui: dict, lang: str) -> list[str]:
    out = ['<a id="packs"></a>', f"## {ui['packs']}", "", ui["packs_note"], ""]
    for p in packs:
        links = " → ".join(
            f"[{display_name(by_repo[r.lower()])}]({gh_url(by_repo[r.lower()]['repo'])})" for r in p["repos"]
        )
        out += [line.format(name=tr(p, "name", lang), goal=tr(p, "goal", lang), links=links, why=tr(p, "why", lang))
                for line in ui["pack"]]
    return out + [""]


def render_group(key: str, group: dict, items: list[dict], meta: dict, ref: dt.date | None, taxonomy: dict,
                 ui: dict, lang: str) -> list[str]:
    stages = taxonomy["stages"]
    out = [f'<a id="group-{key}"></a>', f"### {tr(group, 'label', lang)}", ""]
    if group.get("intro"):
        out += [tr(group, "intro", lang), ""]
    for s in items:
        m = meta.get(s["repo"], {})
        stage_text = " · ".join(tr(st, "short", lang) for k, st in stages.items() if k in s["stages"])
        block = desc_block(s, tr(taxonomy, "models", lang), stage_text, meta_line(s, m, ref, ui), ui, lang)
        out += [f"- {name_line(s, m, ref)}<br>{block}", ""]

    cmds = [(display_name(s), install_cmd(s)) for s in items if install_cmd(s)]
    if cmds:
        out += ["", f"<details><summary>{ui['install']}</summary>", "", "```bash", ui["install_note"]]
        for name, cmd in cmds:
            out += [f"# {name}", cmd]
        out += ["```", "", "</details>"]
    return out + [""]


def new_entries(skills: list[dict], meta: dict, ref: dt.date | None) -> list[dict]:
    if ref is None:
        return []
    def age(s):
        seen = meta.get(s["repo"], {}).get("first_seen")
        return (ref - dt.date.fromisoformat(seen)).days if seen else None
    hits = [s for s in skills if (a := age(s)) is not None and 0 <= a < NEW_DAYS]
    return sorted(hits, key=lambda s: (age(s), -meta.get(s["repo"], {}).get("stars", -1)))


def render_new(items: list[dict], meta: dict, ui: dict, lang: str) -> list[str]:
    out = ['<a id="new"></a>', f"## {ui['new']}", ""]
    if not items:
        return out + [ui["new_none"], ""]
    out += [ui["new_count"].format(days=NEW_DAYS, n=len(items)), ""]
    for s in items:
        stars = meta.get(s["repo"], {}).get("stars")
        star = f" ★{fmt_stars(stars)}" if stars is not None else ""
        out.append(ui["new_item"].format(name=display_name(s), url=gh_url(s["repo"]), star=star,
                                         desc=cell(tr(s, "desc", lang))))
    return out + [""]


def links(items) -> str:
    return " · ".join(f"[{display_name(s)}]({gh_url(s['repo'])})" for s in items)


def render_index(anchor: str, title: str, intro: str, labels: dict[str, str], field: str,
                 skills: list[dict], meta: dict, ui: dict, split: bool = False) -> list[str]:
    """split=True 时每项拆成「专项」和「综合」两行，专项 = 覆盖阶段数 ≤ SPECIALIST_MAX。"""
    out = [f'<a id="{anchor}"></a>', f"## {title}", "", intro, ""]
    for key, label in labels.items():
        hits = by_stars((s for s in skills if key in s.get(field, [])), meta)
        if not hits:
            continue
        if not split:
            out += [ui["index_item"].format(label=label, n=len(hits), links=links(hits)), ""]
            continue
        focused = [s for s in hits if len(s["stages"]) <= SPECIALIST_MAX]
        broad = [s for s in hits if len(s["stages"]) > SPECIALIST_MAX]
        out += [ui["index_head"].format(label=label, n=len(hits)), ""]
        out += [ui["index_line"].format(name=ui[name], n=len(items), links=links(items))
                for name, items in (("focused", focused), ("broad", broad)) if items]
        out += [""]
    return out


